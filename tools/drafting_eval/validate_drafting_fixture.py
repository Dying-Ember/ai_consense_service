#!/usr/bin/env python3
"""Read-only grading of saved real Drafting API responses against the 79-item exam.

The reference answers are used only by this offline scorer, never as model input.
This script performs no HTTP calls, uploads, generation, confirmations, or writes
to application state. It writes only the requested JSON/Markdown scoring reports.
Exit codes: 0 PASS, 1 FAIL, 2 invalid/incomplete grading inputs, 3 REVIEW required.
"""

