def read(path: Path):
    return json.loads(path.read_text(encoding="utf-8-sig"))


def unwrap(path: Path):
    obj = read(path)
    if isinstance(obj, dict) and "code" in obj:
        if obj["code"] != 0:
            raise ValueError(f"{path.name}: unsuccessful API code={obj['code']}: {obj.get('message')}")
        return obj.get("data")
    return obj


def canonical(text: str) -> str:
    return re.sub(r"\s+", " ", text.translate(str.maketrans({"“": '"', "”": '"', "‘": "'", "’": "'", "\u00a0": " "}))).strip()


def present(source: str, quote: str) -> bool:
    return bool(isinstance(quote, str) and quote.strip() and canonical(quote) in canonical(source))


def native_projection(text: str) -> str:
    # DocumentParser renders table-cell boundaries as spaced pipes. Remove only
    # that presentation separator when comparing against native XML paragraphs.
    return re.sub(r"\s+\|\s+", " ", canonical(text))


def exact_text_fidelity(actual, expected, key: str) -> bool:
    """Keep a separate literal-text score without changing the business score."""
    if isinstance(expected, str):
        return isinstance(actual, str) and actual == expected
    if isinstance(expected, dict):
        if not isinstance(actual, dict):
            return False
        return all(k in actual and exact_text_fidelity(actual[k], v, key) for k, v in expected.items())
    if isinstance(expected, list):
        if not isinstance(actual, list) or len(actual) != len(expected):
            return False
        remaining = list(actual)
        for e in expected:
            i = next((i for i, a in enumerate(remaining) if equivalent(a, e, key)), None)
            if i is None or not exact_text_fidelity(remaining.pop(i), e, key):
                return False
        return True
    return equivalent(actual, expected, key)


def decoded(value, kind: str):
    if value is None or isinstance(value, str) and not value.strip():
        return None
    if not isinstance(value, str) or kind in {"text", "date", "choice"}:
        return value
    try:
        return json.loads(value)
    except ValueError:
        return value


def equivalent(actual, expected, key: str) -> bool:
    if isinstance(expected, bool) or expected is None:
        return type(actual) is type(expected) and actual == expected
    if isinstance(expected, (int, float)):
        return not isinstance(actual, bool) and isinstance(actual, (int, float)) and Decimal(str(actual)) == Decimal(str(expected))
    if isinstance(expected, str):
        return isinstance(actual, str) and canonical(actual) == canonical(expected)
    if isinstance(expected, dict):
        if not isinstance(actual, dict):
            return False
        a = dict(actual)
        # IDs generated by the list editor are not tender data. No other field
        # (number, type, description or scope) may be dropped from comparison.
        if key == "billNos" and {"number", "type", "description"}.issubset(expected):
            # Core Bill identity is graded here. Optional placement/trade/purpose
            # metadata is preserved and separately reported for the usage oracle.
            a = {k: a[k] for k in expected if k in a}
        if key == "sections" and {"designation", "workTypes", "location"}.issubset(expected) and "id" not in expected:
            a.pop("id", None)
        if set(a) != set(expected):
            return False
        return all(
            isinstance(a[k], str) and canonical(a[k]).casefold() == canonical(v).casefold()
            if key == "contractTitle" and k == "title" and isinstance(v, str)
            else equivalent(a[k], v, key)
            for k, v in expected.items()
        )
    if isinstance(expected, list):
        if not isinstance(actual, list) or len(actual) != len(expected):
            return False
        # Catalogue lists/multiselects describe sets of records. Preserve every
        # field and multiplicity while allowing harmless record order changes.
        remaining = list(actual)
        for value in expected:
            match = next((i for i, candidate in enumerate(remaining) if equivalent(candidate, value, key)), None)
            if match is None:
                return False
            remaining.pop(match)
        return not remaining
    return type(actual) is type(expected) and actual == expected


def subset(actual, expected, key: str) -> bool:
    if not isinstance(expected, list) or not isinstance(actual, list) or not actual or len(actual) > len(expected):
        return False
    remaining = list(expected)
    for value in actual:
        match = next((i for i, e in enumerate(remaining) if equivalent(value, e, key)), None)
        if match is None:
            return False
        remaining.pop(match)
    return True


def semantic_diagnostic(key: str, value, quote: str, evidence: dict, name: str, paragraphs: dict) -> dict:
    """Conservative diagnostics, not a second LLM or a broad semantic oracle."""
    reference_quote = evidence.get("quote", "")
    same_file = bool(evidence) and name == evidence.get("file")
    overlap = present(quote, reference_quote) or present(reference_quote, quote)
    # A generic prefix of an answer paragraph is not the answer. Require the
    # candidate quotation to contain the COMPLETE curated reference statement.
    informative_overlap = present(quote, reference_quote) and len(canonical(reference_quote)) >= 20
    occurrence_count = canonical("\n".join(paragraphs.get(name, []))).count(canonical(reference_quote)) if reference_quote else 0
    exact_unique_anchor = same_file and canonical(quote) == canonical(reference_quote) and occurrence_count == 1

    def leaves(v):
        if isinstance(v, str):
            return [v]
        if isinstance(v, (int, float)) and not isinstance(v, bool):
            return [str(v)]
        if isinstance(v, dict):
            return [leaf for k, x in v.items() if k != "id" for leaf in leaves(x)]
        if isinstance(v, list):
            return [leaf for x in v for leaf in leaves(x)]
        return []

    terms = leaves(value)
    literal_values = bool(terms) and all(
        bool(re.search(r"(?<![\d.])" + re.escape(t) + r"(?![\d.])", quote)) if re.fullmatch(r"\d+(?:\.\d+)?", t)
        else canonical(t) in canonical(quote)
        for t in terms
    )
    # Strings such as 'none', or booleans, need a field-specific anchor. Long
    # business wording, full structured records and numeric rates can use literal
    # value support, but a number with an unrelated short quote stays unverified.
    numeric_scope_cue = (
        bool(re.search(r"\bup\s+to\s+(?:size\s+)?a3\b", quote, re.I)) if key == "photocopyRateUpToA3"
        else bool(re.search(r"\b(?:period|duration|months?)\b", quote, re.I)) if key == "contractPeriodMonths"
        else False
    )
    def has_boolean(v):
        return isinstance(v, bool) or isinstance(v, dict) and any(has_boolean(x) for x in v.values()) or isinstance(v, list) and any(has_boolean(x) for x in v)

    distinctive_values = literal_values and (
        isinstance(value, (dict, list)) and bool(terms) and not has_boolean(value)
        or isinstance(value, str) and len(canonical(value)) >= 12
        # A base period or ceiling is not an adopted exact draft period.
        # Exact period must use the curated adoption statement or manual review.
        or isinstance(value, (int, float)) and not isinstance(value, bool) and key != "contractPeriodMonths" and numeric_scope_cue and len(canonical(quote)) >= 20
    )
    verified = (same_file and informative_overlap) or exact_unique_anchor or distinctive_values
    return {
        "verdict": "SUPPORTED_BY_LITERAL_DIAGNOSTIC" if verified else "HUMAN_REVIEW_REQUIRED",
        "referenceFileMatch": same_file, "referenceQuoteOverlap": overlap,
        "informativeReferenceOverlap": informative_overlap,
        "exactUniqueReferenceAnchor": exact_unique_anchor,
        "allLiteralBusinessLeavesInQuote": literal_values,
        "numericFieldScopeCue": numeric_scope_cue,
        "structuredBooleanRolesPresent": has_boolean(value),
        "boundary": "Literal/reference diagnostics do not establish full contractual semantic entailment; review the quoted source and any supersession relationships.",
    }


def native_paragraphs(path: Path) -> list[str]:
    return native_evidence(path)["legacyParagraphs"]


def native_evidence(path: Path) -> dict:
    with zipfile.ZipFile(path) as doc:
        document = ET.fromstring(doc.read("word/document.xml"))
    # Native ordinal includes table-cell paragraphs, matching this fixture's
    # nativeParagraph anchors; top-level python-docx paragraphs omit them.
    # OOXML stores an explicit line break or tab between w:t nodes. Preserve
    # those separators: concatenating only w:t fuses adjacent words and makes
    # literal quotations from a valid multi-line paragraph appear absent.
    tokens = {
        f"{{{NS['w']}}}br": "\n",
        f"{{{NS['w']}}}cr": "\n",
        f"{{{NS['w']}}}tab": "\t",
    }
    def paragraph_text(paragraph):
        return "".join(node.text or "" if node.tag == f"{{{NS['w']}}}t" else tokens.get(node.tag, "") for node in paragraph.iter())
    body = document.find("w:body", NS)
    if body is None:
        raise ValueError("DOCX is missing its native document body")
    legacy = [paragraph_text(p) for p in body.findall(".//w:p", NS)]
    paragraphs, tables, projection = [], [], []
    for element in body:
        if element.tag == f"{{{NS['w']}}}p":
            text = paragraph_text(element)
            paragraphs.append(text)
            projection.append(text)
        elif element.tag == f"{{{NS['w']}}}tbl":
            rows = [["\n".join(paragraph_text(p) for p in cell.findall("w:p", NS))
                     for cell in row.findall("w:tc", NS)]
                    for row in element.findall("w:tr", NS)]
            tables.append(rows)
            projection.extend(" | ".join(row) for row in rows)
    return {"legacyParagraphs": legacy, "paragraphs": paragraphs,
            "tables": tables, "projection": projection}


def reference_evidence_verified(evidence: dict, native: dict, file_hash: str) -> bool:
    """Verify declared OOXML anchors, preserving legacy all-paragraph ordinals."""
    if file_hash != evidence.get("sha256"):
        return False
    table = evidence.get("sourceKind") == "table"
    if table:
        ordinal = evidence.get("nativeTable")
        tables = native.get("tables", [])
        if "nativeParagraph" in evidence or type(ordinal) is not int or not 1 <= ordinal <= len(tables):
            return False
        actual = tables[ordinal - 1]
        expected = [evidence.get("headers")] + (evidence.get("rows") or [])
        if not actual or any(not isinstance(row, list) or any(not isinstance(cell, str) for cell in row) for row in expected):
            return False
        if [[canonical(cell) for cell in row] for row in actual] != [[canonical(cell) for cell in row] for row in expected]:
            return False
        return canonical("\n".join(" | ".join(row) for row in actual)) == canonical(evidence.get("quote", ""))
    if "nativeTable" in evidence or evidence.get("sourceKind") not in (None, "paragraph"):
        return False
    paragraphs = native.get("paragraphs" if evidence.get("sourceKind") == "paragraph" else "legacyParagraphs", [])
    ordinal = evidence.get("nativeParagraph")
    return type(ordinal) is int and 1 <= ordinal <= len(paragraphs) and canonical(paragraphs[ordinal - 1]) == canonical(evidence.get("quote", ""))


def sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def local_optional(run: Path, name: str, default):
    path = run / name
    return unwrap(path) if path.is_file() else default


def fixture_presentation(expected_doc: dict, expected: dict) -> dict:
    """Use offline fixture metadata for labels, never for scoring decisions.

    The fixed catalogue/evidence checks below still grade every expected input.
    A new fixture may have different Bill identities and business boundaries;
    those facts must not inherit the original exam's Bill 9/10/11 assumptions.
    """
    metadata = expected_doc.get("gradingMetadata", {})
    if not isinstance(metadata, dict):
        raise ValueError("gradingMetadata must be an object")
    text_defaults = {
        "examTitle": "Drafting 79 项缺失证据考题",
        "candidateExamScope": "Real saved Drafting candidate identification on the missing-evidence 15-DOCX exam; no adoption or document generation acceptance.",
        "additionalBusinessBoundary": "Candidate identification does not establish correct Bill distribution or usage, safety component links, effective standard terms or duplicate-free generated wording. Any additional business oracle below belongs to this fixture and remains unevaluated.",
    }
    result = {}
    for key, default in text_defaults.items():
        value = metadata.get(key, default)
        if not isinstance(value, str) or not value.strip():
            raise ValueError(f"gradingMetadata.{key} must be a nonempty string")
        result[key] = value
    notes = metadata.get("additionalBusinessNotes", [])
    if not isinstance(notes, list) or any(not isinstance(note, str) or not note.strip() for note in notes):
        raise ValueError("gradingMetadata.additionalBusinessNotes must be a list of nonempty strings")
    result["additionalBusinessNotes"] = notes
    bills = expected.get("billNos", {}).get("value")
    result["billCount"] = len(bills) if isinstance(bills, list) else None
    return result


def fixture_holdouts(expected: dict, catalog: dict) -> set[str]:
    """Validate this exam's declared holdouts without fixing their identities.

    The saved API catalogue fixes the 79 input keys. A new exam may disclose
    an old holdout and withhold another active input; null/unknown and the
    four-item boundary remain mandatory.
    """
    keys = [field["key"] for group in catalog.get("groups", []) for field in group.get("fields", [])]
    if (not isinstance(expected, dict) or len(expected) != 79
            or len(keys) != 79 or len(set(keys)) != 79 or set(expected) != set(keys)):
        raise ValueError("Reference must contain exactly the 79 catalogue inputs, with unique catalogue keys")
    if any(not isinstance(truth, dict) for truth in expected.values()):
        raise ValueError("Reference input declarations must be objects")
    withheld = {key for key, truth in expected.items() if truth.get("origin") == "deliberately_withheld"}
    if len(withheld) != 4:
        raise ValueError("Reference must declare exactly four deliberately withheld inputs")
    if any(expected[key].get("status") != "unknown" or expected[key].get("applicability") != "active"
           or "value" not in expected[key] or expected[key]["value"] is not None for key in withheld):
        raise ValueError("Declared holdouts must be active unknown null inputs")
    return withheld


def grade(args) -> tuple[dict, int]:
    fixture = args.fixture.resolve()
    reference = fixture / "02_reference_do_not_upload" if (fixture / "02_reference_do_not_upload").is_dir() else fixture
    upload_dir = reference.parent / "01_upload_documents"
    expected_path = reference / "expected_values.json"
    expected_doc = read(expected_path)
    expected = expected_doc["expectedInputs"]
    run = args.actual.resolve().parent
    catalog = local_optional(run, "catalog.json", {})
    if not catalog:
        raise ValueError("catalog.json API snapshot is required; the raw resource ruleVersion may differ from the running Java/API catalogue version")
    withheld = fixture_holdouts(expected, catalog)
    # Read the incremental ledger solely to verify withheld answers never leak
    # into any staged answer; this grader evaluates the final 15-document state.
    incremental = read(reference / "incremental_expected_states.json")
    if len(incremental) != 15 or any(
        k in stage.get("newAnswers", {}) or stage.get("cumulativeValues", {}).get(k) is not None
        for stage in incremental for k in withheld
    ):
        raise ValueError("Reference incremental states violate the missing-evidence boundary")

    variables = unwrap(args.actual)
    trace = unwrap(args.trace) if args.trace else local_optional(run, "trace.json", {})
    plan = unwrap(args.plan) if args.plan else local_optional(run, "plan.json", {})
    inputs = local_optional(run, "inputs.json", [])
    manifest = read(run / "manifest.json") if (run / "manifest.json").is_file() else {}
    stage_text = str(args.stage or manifest.get("stage") or "SIM15")
    stage_match = re.fullmatch(r"(?:SIM)?0*(\d+)", stage_text, re.I)
    if not stage_match or not 1 <= int(stage_match.group(1)) <= 15:
        raise ValueError("stage must be SIM01..SIM15 or 1..15")
    stage_number = int(stage_match.group(1))
    stage_truth = incremental[stage_number - 1]
    expected = {k: dict(v) for k, v in expected.items()}
    for key, truth in expected.items():
        previous = truth["value"]
        truth["value"] = stage_truth["cumulativeValues"].get(key)
        truth["applicability"] = stage_truth.get("applicability", {}).get(key, truth.get("applicability"))
        if stage_number < 15 and previous is not None and truth["value"] is None:
            truth["status"] = "not_yet_disclosed"
        elif stage_number < 15 and truth["status"] == "not_applicable" and truth["applicability"] == "prerequisite_unknown":
            truth["status"] = "prerequisite_unknown"
    presentation = fixture_presentation(expected_doc, expected)
    if not isinstance(variables, list) or not isinstance(trace, dict) or not isinstance(plan, dict):
        raise ValueError("variables must be a VariableVO list; trace and plan must be objects")
    by_key = {v.get("key"): v for v in variables}
    kinds = {f["key"]: f["kind"] for g in catalog.get("groups", []) for f in g.get("fields", [])}
    kinds.update({f["key"]: f["kind"] for f in catalog.get("systemFields", [])})
    identities = {str(s["id"]): s for s in plan.get("sourceIdentities", [])}
    input_ids = {str(i["id"]): i for i in inputs if "id" in i}
    parts = trace.get("parts", [])
    source_texts: dict[str, list[str]] = {}
    for part in parts:
        doc_id = str(part.get("sourceDocumentId"))
        source_texts.setdefault(doc_id, []).append(part.get("sourceText") or "")
        context = part.get("context") or {}
        if context.get("sourceText"):
            source_texts[doc_id].append(context["sourceText"])
        for attempt in part.get("attempts", []):
            context = attempt.get("context") or {}
            if context.get("sourceText"):
                source_texts[doc_id].append(context["sourceText"])

    all_fixture_files = {p.name: p for p in upload_dir.glob("*.docx")}
    expected_files = dict(sorted(all_fixture_files.items())[:stage_number])
    manifests = {entry.get("name") or Path(entry["path"]).name: entry for entry in manifest.get("inputFiles", [])}
    file_hashes = {name: sha(path) for name, path in all_fixture_files.items()}
    native = {name: native_evidence(path) for name, path in all_fixture_files.items()}
    paragraphs = {name: structure["projection"] for name, structure in native.items()}
    global_failures = []
    boundary = {
        "exact_15_fixture_docx": len(all_fixture_files) == 15,
        "manifest_exact_fixture_inventory": set(manifests) == set(expected_files),
        "actual_inputs_exact_fixture_inventory": Counter(i.get("fileName") for i in inputs) == Counter(expected_files.keys()),
        "manifest_byte_hashes_match_fixture": bool(manifests) and all(manifests.get(n, {}).get("sha256") == file_hashes[n] for n in expected_files),
        "trace_completed": trace.get("status") == "completed",
        "trace_not_stale": trace.get("stale") is False,
        "trace_revision_matches_current_plan": bool(trace.get("evidenceRevision")) and trace.get("evidenceRevision") == plan.get("evidenceRevision"),
        "no_auto_adoption": all(v.get("confirmed") is False and v.get("manuallyEdited") is False for v in variables if v.get("key") in expected),
        "no_unadopted_effective_values": not any(k in plan.get("effectiveValues", {}) for k in expected),
        "unique_variable_keys": len(by_key) == len(variables),
        "all_79_variable_rows_present": set(expected).issubset(by_key),
        "source_catalogue_version_matches": catalog.get("ruleVersion") == expected_doc.get("catalogueRuleVersion"),
        "no_hidden_target_override_populated": not any(v.get("value") or v.get("candidates") or v.get("confirmed") or v.get("manuallyEdited") for v in variables if v.get("key") in {"targetOverrides", "targetEdits"}),
    }
    for check, ok in boundary.items():
        if not ok:
            global_failures.append(check)
    if manifest.get("errors"):
        global_failures.append("runner_reported_errors")

    ledger = []
    for key, truth in expected.items():
        v = by_key.get(key)
        wanted = truth["value"]
        kind = kinds.get(key, v.get("kind", "") if v else "")
        evidence = truth.get("inputEvidence") or {}
        ref_ok = True
        if evidence:
            ref_ok = reference_evidence_verified(evidence, native.get(evidence["file"], {}), file_hashes.get(evidence["file"]))
        candidates = []
        covered = []
        correct_full = False
        wrong_latest = 0
        historical = 0
        ungrounded = 0
        semantic_full = False
        semantic_covered = []
        for index, c in enumerate((v or {}).get("candidates") or []):
            value = decoded(c.get("value"), kind)
            doc_id = str(c.get("sourceDocumentId"))
            identity = identities.get(doc_id, {})
            input_row = input_ids.get(doc_id, {})
            name = c.get("fileName")
            quote = c.get("sourceQuote") or ""
            grounds = {
                "source_is_uploaded_project_input": identity.get("category") == "PROJECT_INPUT" and name in expected_files and input_row.get("fileName") == name,
                "source_identity_matches": bool(c.get("sourceHash")) and c.get("sourceHash") == identity.get("hash") and name == identity.get("fileName"),
                "literal_quote_present_in_live_trace": any(present(text, quote) for text in source_texts.get(doc_id, [])),
                "literal_quote_present_in_native_docx_projection": bool(quote.strip()) and native_projection(quote) in native_projection("\n".join(paragraphs.get(name, []))),
                "uploaded_docx_byte_hash_matches_fixture": name in file_hashes and manifests.get(name, {}).get("sha256") == file_hashes.get(name),
            }
            grounded = all(grounds.values())
            matches = wanted is not None and equivalent(value, wanted, key)
            partial = wanted is not None and subset(value, wanted, key)
            semantic = semantic_diagnostic(key, value, quote, evidence, name, paragraphs)
            semantic_ok = semantic["verdict"] == "SUPPORTED_BY_LITERAL_DIAGNOSTIC"
            if not grounded:
                ungrounded += 1
                classification = "ungrounded"
            elif matches:
                classification = "correct_full"
                correct_full = True
                semantic_full = semantic_full or semantic_ok
            elif partial:
                classification = "correct_partial"
                covered.extend(value)
                if semantic_ok:
                    semantic_covered.extend(value)
            elif value is None:
                classification = "null_candidate"
            elif evidence and name != evidence.get("file"):
                classification = "historical_or_other_source_conflict_review"
                historical += 1
            else:
                classification = "wrong_authoritative_or_forbidden_value"
                wrong_latest += 1
            candidates.append({
                "index": index, "classification": classification, "value": value,
                "fileName": name, "sourceDocumentId": c.get("sourceDocumentId"),
                "sourceHash": c.get("sourceHash"), "sourceQuote": quote,
                "reason": c.get("reason"), "grounded": grounded, "groundingChecks": grounds,
                "referenceFileMatch": bool(evidence) and name == evidence.get("file"),
                "referenceQuoteOverlap": bool(evidence) and (present(quote, evidence.get("quote", "")) or present(evidence.get("quote", ""), quote)),
                "billExtraMetadata": [{k: val for k, val in row.items() if k not in {"id", "number", "description", "type"}} for row in value if isinstance(row, dict)] if key == "billNos" and isinstance(value, list) else None,
                "semanticEvidenceDiagnostic": semantic,
            })
        union_covers = isinstance(wanted, list) and bool(wanted) and all(any(equivalent(c, e, key) for c in covered) for e in wanted)
        recognized = correct_full or union_covers
        semantic_union = isinstance(wanted, list) and bool(wanted) and all(any(equivalent(c, e, key) for c in semantic_covered) for e in wanted)
        semantic_supported = semantic_full or semantic_union
        raw = (v or {}).get("value")
        observed = decoded(raw, kind)
        failures = []
        warnings = []
        if v is None:
            failures.append("variable_row_missing")
        if not ref_ok:
            failures.append("reference_evidence_anchor_or_file_hash_invalid")
        if v and (v.get("confirmed") is not False or v.get("manuallyEdited") is not False):
            failures.append("automatic_or_preexisting_adoption")
        if wanted is None:
            nonempty_candidates = [c for c in candidates if c["value"] is not None]
            # Keep every null state distinct. Missing is not false, zero, an
            # empty list, or the string 'unknown'; inactive is not missing.
            if raw is not None and (not isinstance(raw, str) or raw.strip()):
                failures.append("expected_unfilled_input_has_value")
            if nonempty_candidates:
                failures.append("expected_unfilled_input_has_filled_candidate")
            if key in withheld and v and v.get("adoptionState") != "missing":
                failures.append("withheld_input_not_editable_missing_state")
            recognized = not failures
        else:
            if not recognized:
                failures.append("correct_grounded_candidate_not_recognized")
            if recognized and observed is None:
                if v and v.get("adoptionState") == "conflict" and not (v.get("confirmed") or v.get("manuallyEdited")):
                    warnings.append("correct_candidate_available_but_conflict_requires_human_choice")
                else:
                    failures.append("correct_candidate_not_prefilled_or_missing_display")
            if observed is not None and not equivalent(observed, wanted, key):
                if v and v.get("adoptionState") == "conflict" and not (v.get("confirmed") or v.get("manuallyEdited")):
                    warnings.append("conflict_requires_human_choice")
                else:
                    failures.append("displayed_suggestion_value_incorrect")
            if recognized and not semantic_supported:
                warnings.append("correct_value_and_literal_source_found_but_semantic_evidence_requires_human_review")
        if any(any(row for row in (c.get("billExtraMetadata") or [])) for c in candidates):
            warnings.append("optional_bill_usage_metadata_not_verified_against_additional_business_oracle")
        if wrong_latest:
            failures.append("wrong_extra_candidate_from_authoritative_or_forbidden_source")
        if ungrounded:
            failures.append("candidate_source_grounding_failed")
        if historical:
            warnings.append("historical_or_other_source_conflicts_require_manual_review")
        if v and v.get("validationIssue"):
            failures.append("application_validation_issue")
        outcome = "FAIL" if failures else "REVIEW" if warnings else "PASS"
        ledger.append({
            "key": key, "expectedStatus": truth["status"], "expectedApplicability": truth.get("applicability"),
            "expectedOrigin": truth.get("origin"), "expectedValue": wanted,
            "expectedEvidence": evidence or None, "referenceEvidenceVerified": ref_ok,
            "observedValue": observed, "rawValue": raw,
            "exactTextFidelity": exact_text_fidelity(observed, wanted, key),
            "confirmed": (v or {}).get("confirmed"), "manuallyEdited": (v or {}).get("manuallyEdited"),
            "adoptionState": (v or {}).get("adoptionState"), "reviewRequired": (v or {}).get("reviewRequired"),
            "recognizedCorrectGroundedAnswer": recognized, "correctFullCandidate": correct_full,
            "semanticallySupportedByLiteralDiagnostic": semantic_supported if wanted is not None else None,
            "correctPartialUnionCoversAnswer": union_covers,
            "candidateCount": len(candidates), "wrongLatestCandidateCount": wrong_latest,
            "historicalOrOtherSourceConflictCount": historical, "ungroundedCandidateCount": ungrounded,
            "candidates": candidates, "outcome": outcome, "failures": failures, "warnings": warnings,
        })
    counts = Counter(row["outcome"] for row in ledger)
    verdict = "FAIL" if counts["FAIL"] or global_failures else "REVIEW" if counts["REVIEW"] else "PASS"
    report = {
        "schemaVersion": 1, "gradedAtUtc": datetime.now(timezone.utc).isoformat(),
        "verdict": verdict, "scope": presentation["candidateExamScope"],
        "fixtureDisplayTitle": presentation["examTitle"],
        "referenceNeverSentToModelByThisScorer": True,
        "actualPath": str(args.actual.resolve()), "fixturePath": str(fixture),
        "expectedFileSha256": sha(expected_path), "projectId": manifest.get("projectId"),
        "stage": f"SIM{stage_number:02d}", "uploadedDocumentCountExpected": stage_number,
        "modelIdentity": trace.get("modelIdentity"), "runId": trace.get("runId"),
        "elapsedSeconds": manifest.get("elapsedSeconds"), "boundaryChecks": boundary,
        "globalFailures": global_failures,
        "summary": {
            "totalInputs": len(expected), "requiredValueInputs": sum(v["value"] is not None for v in expected.values()),
            "correctGroundedValueInputsRecognized": sum(r["recognizedCorrectGroundedAnswer"] and r["expectedValue"] is not None for r in ledger),
            "valueInputsWithLiteralSemanticSupport": sum(r["semanticallySupportedByLiteralDiagnostic"] is True for r in ledger),
            "nullStateInputs": sum(v["value"] is None for v in expected.values()),
            "correctlyUnfilledInputs": sum(r["recognizedCorrectGroundedAnswer"] and r["expectedValue"] is None for r in ledger),
            "pass": counts["PASS"], "review": counts["REVIEW"], "fail": counts["FAIL"],
            "withheldPass": sum(r["key"] in withheld and r["outcome"] == "PASS" for r in ledger),
            "wrongLatestCandidates": sum(r["wrongLatestCandidateCount"] for r in ledger),
            "historicalOrOtherSourceConflictCandidates": sum(r["historicalOrOtherSourceConflictCount"] for r in ledger),
            "ungroundedCandidates": sum(r["ungroundedCandidateCount"] for r in ledger),
            "businessValueEqualButLiteralTextDiffers": [r["key"] for r in ledger if r["expectedValue"] is not None and equivalent(r["observedValue"], r["expectedValue"], r["key"]) and not r["exactTextFidelity"]],
            "statusCounts": dict(Counter(v["status"] for v in expected.values())),
        },
        "gradingNotes": [
            "Nonempty unconfirmed suggestions are legitimate. confirmed/manuallyEdited must remain false, and suggestions must not enter plan.effectiveValues.",
            "Grounding checks quote literal presence in both live trace and native DOCX projection, uploaded file byte identity and current project source identity. Native projection removes only parser-rendered spaced table pipes and normalizes whitespace/typographic quotes. This does not independently prove semantic entailment of every value by a quoted sentence; source/quote evidence remains in each ledger item for review.",
            "Candidate sets may contain list fragments; correctly grounded fragments may jointly cover an expected list. Generated billNos IDs and harmless list order are ignored; substantive fields are retained.",
            "Wrong candidates in the authoritative reference file fail. Wrong candidates from a different supplied source remain separately visible and require review, even if a correct candidate was found.",
            "Missing, intentionally unknown, conditionally inactive and optional unchanged inputs retain their distinct expected statuses. Empty lists are answers requiring grounded evidence.",
            f"The Bill core compares all {presentation['billCount']} number/type/formal-description records in this stage's fixture answer." if presentation["billCount"] is not None else "This stage has no disclosed Bill list to compare.",
            "Optional Bill metadata is retained separately; usage, safety component links, generated inspection-text duplication and final drafting remain unaccepted by this scorer.",
        ],
        "additionalBusinessAcceptance": {
            "verdict": "NOT_EVALUATED",
            "billDistributionAndUsageOracle": expected_doc.get("billDistributionAndUsageOracle"),
            "knownRepresentationLimitations": expected_doc.get("knownRepresentationLimitations"),
            "effectiveTermsNotOptionalOverrides": expected_doc.get("effectiveTerms"),
            "boundary": presentation["additionalBusinessBoundary"],
            "fixtureNotes": presentation["additionalBusinessNotes"],
        },
        "ledger": ledger,
    }
    return report, {"PASS": 0, "FAIL": 1, "REVIEW": 3}[verdict]


def markdown(report: dict) -> str:
    s = report["summary"]
    lines = [
        f"# {report.get('fixtureDisplayTitle', 'Drafting 79 项缺失证据考题')}：{report['verdict']}", "",
        f"项目 `{report.get('projectId')}`，识别运行 `{report.get('runId')}`，阶段 `{report.get('stage')}`。", "",
        f"有确定值的 {s['requiredValueInputs']} 项中检出正确且有出处的 {s['correctGroundedValueInputsRecognized']} 项；"
        f"应留空的 {s['nullStateInputs']} 项中正确留空 {s['correctlyUnfilledInputs']} 项；四项刻意缺失通过 {s['withheldPass']}/4。", "",
        f"逐项结果：PASS {s['pass']}、REVIEW {s['review']}、FAIL {s['fail']}。"
        f"错误额外候选 {s['wrongLatestCandidates']}，历史/其他源冲突候选 {s['historicalOrOtherSourceConflictCandidates']}，来源核验失败候选 {s['ungroundedCandidates']}。", "",
        "候选正确检出不等于人工采用。识别阶段应保持 confirmed/manuallyEdited=false；非空、未采用的建议值合法，且不得进入 plan.effectiveValues。", "",
        "参考答案仅供本评分器读取，不作为模型输入。本报告验证识别结果、事实值和来源身份，不证明最终生成文稿质量。", "",
        "## 运行边界", "", "| 检查 | 结果 |", "|---|---|",
    ]
    lines.extend(f"| {k} | {'PASS' if v else 'FAIL'} |" for k, v in report["boundaryChecks"].items())
    if report["globalFailures"]:
        lines += ["", "全局失败：" + ", ".join(report["globalFailures"])]
    lines += ["", "## 全部 79 项逐项证据台账", "", "| 变量 | 期望状态 | 结果 | 正确检出/留空 | 候选数 | 错误/冲突/无出处 |", "|---|---|---|---|---:|---|"]
    for r in report["ledger"]:
        lines.append(f"| `{r['key']}` | {r['expectedStatus']} / {r['expectedApplicability']} | {r['outcome']} | {r['recognizedCorrectGroundedAnswer']} | {r['candidateCount']} | {r['wrongLatestCandidateCount']}/{r['historicalOrOtherSourceConflictCount']}/{r['ungroundedCandidateCount']} |")
    for r in report["ledger"]:
        lines += ["", f"### {r['key']} — {r['outcome']}", "", f"状态 `{r['expectedStatus']}`，适用性 `{r['expectedApplicability']}`，来源类别 `{r['expectedOrigin']}`。", "", "期望值：", "", "```json", json.dumps(r["expectedValue"], ensure_ascii=False, indent=2), "```", "", "当前显示建议值：", "", "```json", json.dumps(r["observedValue"], ensure_ascii=False, indent=2), "```"]
        ref = r["expectedEvidence"]
        if ref:
            anchor = f"第 {ref.get('nativeTable')} 个原生表格" if ref.get("sourceKind") == "table" else f"第 {ref.get('nativeParagraph')} 个原生段落"
            lines += ["", f"参考来源 `{ref['recordId']}` / `{ref['file']}` {anchor}，字节 SHA-256 `{ref['sha256']}`。", "", "> " + ref["quote"].replace("\n", "\n> ")]
        if r["failures"] or r["warnings"]:
            lines += ["", "判定原因：" + "; ".join(r["failures"] + r["warnings"])]
        for c in r["candidates"]:
            lines += ["", f"候选 {c['index']}：`{c['classification']}`，文件 `{c['fileName']}`，文档 ID `{c['sourceDocumentId']}`，当前项目 sourceHash `{c['sourceHash']}`。", "", "```json", json.dumps(c["value"], ensure_ascii=False, indent=2), "```", "", "> " + c["sourceQuote"].replace("\n", "\n> "), "", "来源核验：" + ", ".join(f"{k}={v}" for k, v in c["groundingChecks"].items())]
    acceptance = report["additionalBusinessAcceptance"]
    lines += ["", "## 附加业务验收尚未完成", "", acceptance["boundary"]]
    for note in acceptance.get("fixtureNotes", []):
        lines += ["", note]
    business_data = {key: acceptance[key] for key in ("billDistributionAndUsageOracle", "knownRepresentationLimitations", "effectiveTermsNotOptionalOverrides") if acceptance.get(key) is not None}
    if business_data:
        lines += ["", "本考题参考数据中的附加业务要求（本评分器未验证）：", "", "```json", json.dumps(business_data, ensure_ascii=False, indent=2), "```"]
    lines += ["", "## 评分限制", ""] + ["- " + text for text in report["gradingNotes"]]
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--actual", type=Path, required=True, help="saved variables.json (full ApiResponse or VariableVO array)")
    parser.add_argument("--trace", type=Path)
    parser.add_argument("--plan", type=Path)
    parser.add_argument("--fixture", type=Path, required=True, help="79-input / 15-DOCX fixture directory or its 02_reference_do_not_upload directory")
    parser.add_argument("--stage", help="SIM01..SIM15 or 1..15; defaults to manifest.stage, then SIM15")
    parser.add_argument("--out-dir", type=Path, required=True)
    args = parser.parse_args()
    args.out_dir.mkdir(parents=True, exist_ok=True)
    try:
        report, code = grade(args)
    except (OSError, ValueError, KeyError, TypeError, zipfile.BadZipFile) as exc:
        report = {"verdict": "INPUT_ERROR", "error": str(exc), "scope": "No generation or application write performed"}
        (args.out_dir / "drafting-score.json").write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        print(json.dumps(report, ensure_ascii=False))
        raise SystemExit(2)
    (args.out_dir / "drafting-score.json").write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    (args.out_dir / "drafting-score.md").write_text(markdown(report), encoding="utf-8")
    print(json.dumps({"verdict": report["verdict"], "summary": report["summary"], "globalFailures": report["globalFailures"], "report": str((args.out_dir / 'drafting-score.json').resolve())}, ensure_ascii=False, indent=2))
    raise SystemExit(code)


if __name__ == "__main__":
    main()
